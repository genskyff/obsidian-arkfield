import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root));

const fonts = [
  { family: "Inter", file: "Inter-VF.woff2", style: "normal", weight: "100 900" },
  { family: "Inter", file: "Inter-Italic-VF.woff2", style: "italic", weight: "100 900" },
  { family: "Space Grotesk", file: "SpaceGrotesk-VF.ttf", style: "normal", weight: "300 700" },
  { family: "Fira Code", file: "FiraCode-VF.woff2", style: "normal", weight: "300 700" },
];

const formats = {
  woff2: { mime: "font/woff2", format: "woff2" },
  ttf: { mime: "font/ttf", format: "truetype" },
};

const faces = fonts.map(({ family, file, style, weight }) => {
  const { mime, format } = formats[file.split(".").pop()];
  const data = read(`fonts/${file}`).toString("base64");
  return `@font-face {
  font-family: "${family}";
  src: url("data:${mime};base64,${data}") format("${format}");
  font-style: ${style};
  font-weight: ${weight};
}
`;
});

const banner =
  "/* Generated by scripts/build.mjs from arkfield.css and fonts/. Do not edit. */\n\n";
const source = read("arkfield.css").toString("utf8");
const css = `${banner}${source}\n/* Embedded fonts (SIL Open Font License 1.1, see fonts/) */\n\n${faces.join("\n")}`;

const formatted = execSync("oxfmt --stdin-filepath=theme/theme.css", {
  cwd: fileURLToPath(root),
  input: css,
  maxBuffer: 16 * 1024 * 1024,
});
writeFileSync(new URL("theme/theme.css", root), formatted);
console.log(`theme.css built (${fonts.length} fonts embedded)`);
